"""Turn processed metrics into a results summary (docs/results_summary.md).

Reads only real CSVs under experiments/results/processed/<test>/ and writes a
Markdown summary with the headline numbers and the main tables. Fails loudly if
inputs are missing rather than inventing values.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]


def fmt(x, pct=False, nd=3):
    if x is None or (isinstance(x, float) and pd.isna(x)):
        return "n/a"
    return f"{x*100:.1f}%" if pct else f"{x:.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--test", default="test")
    args = ap.parse_args()
    proc = ROOT / "experiments/results/processed" / args.test
    wm = pd.read_csv(proc / "window_metrics.csv")
    ov = wm[wm.scope == "overall"].set_index("method")
    lines = ["# Results Summary (auto-generated from real experiment outputs)\n",
             f"Test campaign: `{args.test}`. Generated by build_paper_tables.py.\n",
             "## Window-level (overall, held-out test)\n",
             "| method | recall | specificity | FPR | precision | F1 | balanced acc | ROC-AUC | PR-AUC |",
             "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    order = [m for m in ["flow_ml_only_raw", "rule_statistical", "abl_ml", "abl_ml_src", "abl_ml_rate",
                         "abl_ml_src_rate", "full_temporal", "proposed"] if m in ov.index]
    for m in order:
        r = ov.loc[m]
        lines.append(f"| {m} | {fmt(r.recall)} | {fmt(r.specificity)} | {fmt(r.fpr)} | {fmt(r.get('precision'))} | "
                     f"{fmt(r.f1)} | {fmt(r.balanced_accuracy)} | {fmt(r.get('roc_auc'))} | {fmt(r.get('pr_auc'))} |")

    # per-protocol for proposed vs flow-ml
    lines += ["\n## Per-protocol FPR / recall (proposed vs flow-ML)\n",
              "| scope | method | recall | FPR |", "|---|---|---:|---:|"]
    for scope in ["proto:udp", "proto:tcp", "proto:icmp"]:
        for m in ["flow_ml_only_raw", "proposed"]:
            sub = wm[(wm.scope == scope) & (wm.method == m)]
            if len(sub):
                r = sub.iloc[0]
                lines.append(f"| {scope} | {m} | {fmt(r.recall)} | {fmt(r.fpr)} |")

    ev = proc / "event_summary.csv"
    placeholders = {}
    if ev.exists():
        es = pd.read_csv(ev).set_index("method")
        lines += ["\n## Event-level (detection latency / false alerts / recovery)\n",
                  "| method | detection rate | mean latency (s) | false alerts/benign run | mean recovery (s) |",
                  "|---|---:|---:|---:|---:|"]
        for m in [x for x in order if x in es.index]:
            r = es.loc[m]
            lines.append(f"| {m} | {fmt(r.detection_rate)} | {fmt(r.mean_latency_s)} | "
                         f"{fmt(r.get('mean_false_alerts_benign_run'))} | {fmt(r.get('mean_recovery_s'))} |")
        if "proposed" in es.index:
            placeholders["latency_proposed"] = fmt(es.loc["proposed", "mean_latency_s"])
            placeholders["recovery"] = fmt(es.loc["proposed", "mean_recovery_s"])

    mit = proc / "mitigation_effect.csv"
    if mit.exists():
        me = pd.read_csv(mit)
        lines += ["\n## Mitigation effect on legitimate probe (during attack)\n",
                  "| condition | probe goodput (Mbit/s) | loss % | jitter ms | RTT ms (p95) |",
                  "|---|---:|---:|---:|---:|"]
        for _, r in me.iterrows():
            lines.append(f"| {r.condition} | {fmt(r.probe_udp_goodput_mbps)} | {fmt(r.probe_loss_pct)} | "
                         f"{fmt(r.get('probe_jitter_ms'))} | {fmt(r.get('ping_rtt_ms_p95'))} |")

    if "proposed" in ov.index and "flow_ml_only_raw" in ov.index:
        placeholders.update({
            "fpr_flow": fmt(ov.loc["flow_ml_only_raw", "fpr"], pct=True),
            "fpr_proposed": fmt(ov.loc["proposed", "fpr"], pct=True),
            "recall_proposed": fmt(ov.loc["proposed", "recall"], pct=True),
        })
    lines += ["\n## Abstract placeholders\n", "```", *[f"{k} = {v}" for k, v in placeholders.items()], "```\n"]
    out = ROOT / "docs" / "results_summary.md"
    out.write_text("\n".join(lines))
    print("wrote", out)
    print("\n".join(lines[:40]))


if __name__ == "__main__":
    main()
